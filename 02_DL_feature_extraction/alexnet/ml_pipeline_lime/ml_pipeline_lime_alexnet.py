# ============================================================
# ML PIPELINE + LIME EXPLAINER - ALEXNET FEATURES
# ============================================================
#
# Purpose:
#   1. Load page-level AlexNet features
#   2. Build ML pipelines
#   3. Train classical ML classifiers
#   4. Evaluate classifier performance
#   5. Compare classifiers
#   6. Apply LIME to the best classifier
#   7. Save LIME explanations
#
# AlexNet is NOT trained here.
# AlexNet was used only for feature extraction.
#
# Input:
#   ../features/X_train_page.npy
#   ../features/y_train_page.npy
#   ../features/X_test_page.npy
#   ../features/y_test_page.npy
#
# Output:
#   results/pipeline_classifier_comparison.csv
#   results/lime_<classifier>_sample_<index>.html
#   results/lime_<classifier>_sample_<index>.txt
#
# ============================================================


# ============================================================
# IMPORTS
# ============================================================

from pathlib import Path

import numpy as np
import pandas as pd

from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from sklearn.svm import SVC
from sklearn.neighbors import KNeighborsClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.naive_bayes import GaussianNB
from sklearn.tree import DecisionTreeClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.ensemble import AdaBoostClassifier

from xgboost import XGBClassifier

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report
)

from lime.lime_tabular import LimeTabularExplainer


# ============================================================
# CONFIGURATION
# ============================================================

FEATURE_DIR = Path("../features")

RESULTS_DIR = Path("results")

RESULTS_DIR.mkdir(
    parents=True,
    exist_ok=True
)

# Test sample to explain using LIME
LIME_SAMPLE_INDEX = 0

# Number of features shown by LIME
LIME_NUM_FEATURES = 10

# Number of samples generated by LIME
LIME_NUM_SAMPLES = 5000


# ============================================================
# LOAD PAGE-LEVEL FEATURES
# ============================================================

print("=" * 60)
print("ALEXNET ML PIPELINE + LIME")
print("=" * 60)

print("\nLoading page-level AlexNet features...")


X_train = np.load(
    FEATURE_DIR /
    "X_train_page.npy"
)

y_train = np.load(
    FEATURE_DIR /
    "y_train_page.npy"
)

X_test = np.load(
    FEATURE_DIR /
    "X_test_page.npy"
)

y_test = np.load(
    FEATURE_DIR /
    "y_test_page.npy"
)


# ============================================================
# PRINT DATASET INFORMATION
# ============================================================

print("\nDataset information:")

print(
    f"Training features shape: {X_train.shape}"
)

print(
    f"Training labels shape:   {y_train.shape}"
)

print(
    f"Testing features shape:  {X_test.shape}"
)

print(
    f"Testing labels shape:    {y_test.shape}"
)


# ============================================================
# CONVERT TO DATAFRAME
# ============================================================
#
# LIME works conveniently with named features.
#
# AlexNet produces 4096-dimensional features.
#


feature_names = [
    f"AlexNet_Feature_{i + 1}"
    for i in range(X_train.shape[1])
]


X_train = pd.DataFrame(
    X_train,
    columns=feature_names
)

X_test = pd.DataFrame(
    X_test,
    columns=feature_names
)

y_train = pd.Series(
    y_train,
    name="Writer"
)

y_test = pd.Series(
    y_test,
    name="Writer"
)


print(
    f"\nNumber of features: {len(feature_names)}"
)

print(
    f"Number of classes: {y_train.nunique()}"
)


# ============================================================
# CLASSIFIERS
# ============================================================
#
# The classifier settings follow the existing
# 03_train_classifiers.py.
#
# Pipeline structure:
#
#     StandardScaler
#           ↓
#       Classifier
#
# For tree-based classifiers, scaling is not required.
# Therefore "passthrough" is used so that the classifier
# behavior remains consistent with the existing code.
#
# ============================================================


classifiers = {

    # --------------------------------------------------------
    # SVM - RBF
    # --------------------------------------------------------

    "SVM_RBF": Pipeline([
        (
            "scaler",
            StandardScaler()
        ),
        (
            "classifier",
            SVC(
                kernel="rbf",
                C=10,
                gamma="scale",
                probability=True
            )
        )
    ]),


    # --------------------------------------------------------
    # SVM - Linear
    # --------------------------------------------------------

    "SVM_LINEAR": Pipeline([
        (
            "scaler",
            StandardScaler()
        ),
        (
            "classifier",
            SVC(
                kernel="linear",
                C=1,
                probability=True
            )
        )
    ]),


    # --------------------------------------------------------
    # KNN - 3
    # --------------------------------------------------------

    "KNN_3": Pipeline([
        (
            "scaler",
            StandardScaler()
        ),
        (
            "classifier",
            KNeighborsClassifier(
                n_neighbors=3
            )
        )
    ]),


    # --------------------------------------------------------
    # KNN - 5
    # --------------------------------------------------------

    "KNN_5": Pipeline([
        (
            "scaler",
            StandardScaler()
        ),
        (
            "classifier",
            KNeighborsClassifier(
                n_neighbors=5
            )
        )
    ]),


    # --------------------------------------------------------
    # RANDOM FOREST
    # --------------------------------------------------------

    "RANDOM_FOREST": Pipeline([
        (
            "scaler",
            "passthrough"
        ),
        (
            "classifier",
            RandomForestClassifier(
                n_estimators=200,
                random_state=42,
                n_jobs=-1
            )
        )
    ]),


    # --------------------------------------------------------
    # LOGISTIC REGRESSION
    # --------------------------------------------------------

    "LOGISTIC_REGRESSION": Pipeline([
        (
            "scaler",
            StandardScaler()
        ),
        (
            "classifier",
            LogisticRegression(
                max_iter=3000,
                random_state=42
            )
        )
    ]),


    # --------------------------------------------------------
    # NAIVE BAYES
    # --------------------------------------------------------

    "NAIVE_BAYES": Pipeline([
        (
            "scaler",
            "passthrough"
        ),
        (
            "classifier",
            GaussianNB()
        )
    ]),


    # --------------------------------------------------------
    # DECISION TREE
    # --------------------------------------------------------

    "DECISION_TREE": Pipeline([
        (
            "scaler",
            "passthrough"
        ),
        (
            "classifier",
            DecisionTreeClassifier(
                max_depth=20,
                random_state=42
            )
        )
    ]),


    # --------------------------------------------------------
    # XGBOOST
    # --------------------------------------------------------

    "XGBOOST": Pipeline([
        (
            "scaler",
            "passthrough"
        ),
        (
            "classifier",
            XGBClassifier(
                n_estimators=200,
                max_depth=6,
                learning_rate=0.05,
                subsample=0.8,
                colsample_bytree=0.8,
                random_state=42,
                n_jobs=-1,
                eval_metric="mlogloss"
            )
        )
    ]),


    # --------------------------------------------------------
    # MLP
    # --------------------------------------------------------

    "MLP": Pipeline([
        (
            "scaler",
            StandardScaler()
        ),
        (
            "classifier",
            MLPClassifier(
                hidden_layer_sizes=(128,),
                max_iter=1000,
                random_state=42
            )
        )
    ]),


    # --------------------------------------------------------
    # ADABOOST
    # --------------------------------------------------------

    "ADABOOST": Pipeline([
        (
            "scaler",
            "passthrough"
        ),
        (
            "classifier",
            AdaBoostClassifier(
                n_estimators=200,
                learning_rate=0.5,
                random_state=42
            )
        )
    ])
}


# ============================================================
# TRAIN AND EVALUATE
# ============================================================

results = []


for name, pipeline in classifiers.items():

    print("\n")
    print("=" * 60)
    print(
        f"TRAINING: {name}"
    )
    print("=" * 60)


    # --------------------------------------------------------
    # TRAIN
    # --------------------------------------------------------

    pipeline.fit(
        X_train,
        y_train
    )


    # --------------------------------------------------------
    # PREDICT
    # --------------------------------------------------------

    predictions = pipeline.predict(
        X_test
    )


    # --------------------------------------------------------
    # METRICS
    # --------------------------------------------------------

    accuracy = accuracy_score(
        y_test,
        predictions
    )

    precision = precision_score(
        y_test,
        predictions,
        average="macro",
        zero_division=0
    )

    recall = recall_score(
        y_test,
        predictions,
        average="macro",
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        predictions,
        average="macro",
        zero_division=0
    )


    # --------------------------------------------------------
    # PRINT RESULTS
    # --------------------------------------------------------

    print(
        f"\nAccuracy : "
        f"{accuracy * 100:.2f}%"
    )

    print(
        f"Precision: "
        f"{precision * 100:.2f}%"
    )

    print(
        f"Recall   : "
        f"{recall * 100:.2f}%"
    )

    print(
        f"F1-score : "
        f"{f1 * 100:.2f}%"
    )


    # --------------------------------------------------------
    # CLASSIFICATION REPORT
    # --------------------------------------------------------

    print("\nClassification Report:")

    print(
        classification_report(
            y_test,
            predictions,
            zero_division=0
        )
    )


    # --------------------------------------------------------
    # STORE RESULTS
    # --------------------------------------------------------

    results.append(
        {
            "Classifier": name,
            "Accuracy": accuracy,
            "Precision": precision,
            "Recall": recall,
            "F1": f1
        }
    )


# ============================================================
# RESULTS TABLE
# ============================================================

results_df = pd.DataFrame(
    results
)

results_df = results_df.sort_values(
    "Accuracy",
    ascending=False
)


print("\n")
print("=" * 60)
print("FINAL ML PIPELINE COMPARISON")
print("=" * 60)

print(
    results_df.to_string(
        index=False
    )
)


# ============================================================
# SAVE RESULTS
# ============================================================

results_path = (
    RESULTS_DIR /
    "pipeline_classifier_comparison.csv"
)

results_df.to_csv(
    results_path,
    index=False
)

print(
    f"\nResults saved to:"
)

print(
    results_path
)


# ============================================================
# FIND BEST CLASSIFIER
# ============================================================

best_classifier_name = (
    results_df.iloc[0]["Classifier"]
)

best_pipeline = classifiers[
    best_classifier_name
]


print("\n")
print("=" * 60)
print("BEST CLASSIFIER")
print("=" * 60)

print(
    f"\nBest classifier: "
    f"{best_classifier_name}"
)

print(
    f"Accuracy: "
    f"{results_df.iloc[0]['Accuracy'] * 100:.2f}%"
)


# ============================================================
# LIME EXPLAINER
# ============================================================

print("\n")
print("=" * 60)
print("LIME EXPLANATION")
print("=" * 60)


# ------------------------------------------------------------
# CHECK SAMPLE INDEX
# ------------------------------------------------------------

if (
    LIME_SAMPLE_INDEX < 0
    or
    LIME_SAMPLE_INDEX >= len(X_test)
):

    raise IndexError(
        f"LIME_SAMPLE_INDEX must be between "
        f"0 and {len(X_test) - 1}"
    )


# ------------------------------------------------------------
# GET CLASSIFIER
# ------------------------------------------------------------

classifier = (
    best_pipeline.named_steps[
        "classifier"
    ]
)


# ------------------------------------------------------------
# CLASS NAMES
# ------------------------------------------------------------

class_names = [
    str(class_name)
    for class_name in classifier.classes_
]


# ------------------------------------------------------------
# CREATE LIME EXPLAINER
# ------------------------------------------------------------

explainer = LimeTabularExplainer(

    training_data=X_train.to_numpy(),

    feature_names=X_train.columns.tolist(),

    class_names=class_names,

    mode="classification",

    discretize_continuous=True,

    random_state=42
)


# ============================================================
# SELECT TEST SAMPLE
# ============================================================

sample = X_test.iloc[
    LIME_SAMPLE_INDEX
].to_numpy()


sample_dataframe = X_test.iloc[
    [LIME_SAMPLE_INDEX]
]


# ============================================================
# PREDICTION
# ============================================================

prediction = best_pipeline.predict(
    sample_dataframe
)[0]


actual = y_test.iloc[
    LIME_SAMPLE_INDEX
]


print(
    f"\nTest sample index: "
    f"{LIME_SAMPLE_INDEX}"
)

print(
    f"Actual writer: "
    f"{actual}"
)

print(
    f"Predicted writer: "
    f"{prediction}"
)


# ============================================================
# PREDICTED CLASS INDEX
# ============================================================

class_index = list(
    classifier.classes_
).index(
    prediction
)


# ============================================================
# GENERATE LIME EXPLANATION
# ============================================================

print(
    "\nGenerating LIME explanation..."
)

print(
    "This may take some time because "
    "there are 4096 AlexNet features."
)


explanation = explainer.explain_instance(

    data_row=sample,

    predict_fn=best_pipeline.predict_proba,

    num_features=LIME_NUM_FEATURES,

    labels=[
        class_index
    ],

    num_samples=LIME_NUM_SAMPLES
)


# ============================================================
# PRINT LIME EXPLANATION
# ============================================================

print("\n")
print("=" * 60)
print("TOP LIME FEATURES")
print("=" * 60)

lime_features = explanation.as_list(
    label=class_index
)


for feature, weight in lime_features:

    print(
        f"{feature:<50} "
        f"{weight:+.6f}"
    )


# ============================================================
# SAVE LIME HTML
# ============================================================

html_path = (
    RESULTS_DIR /
    f"lime_{best_classifier_name}"
    f"_sample_{LIME_SAMPLE_INDEX}.html"
)

explanation.save_to_file(
    str(html_path)
)

print(
    f"\nLIME HTML explanation saved to:"
)

print(
    html_path
)


# ============================================================
# SAVE LIME TEXT
# ============================================================

text_path = (
    RESULTS_DIR /
    f"lime_{best_classifier_name}"
    f"_sample_{LIME_SAMPLE_INDEX}.txt"
)


with open(
    text_path,
    "w",
    encoding="utf-8"
) as f:

    f.write(
        "ALEXNET ML PIPELINE + LIME EXPLANATION\n"
    )

    f.write(
        "=" * 60
        + "\n\n"
    )

    f.write(
        f"Classifier: "
        f"{best_classifier_name}\n"
    )

    f.write(
        f"Test sample index: "
        f"{LIME_SAMPLE_INDEX}\n"
    )

    f.write(
        f"Actual writer: "
        f"{actual}\n"
    )

    f.write(
        f"Predicted writer: "
        f"{prediction}\n"
    )

    f.write(
        f"Predicted class index: "
        f"{class_index}\n\n"
    )

    f.write(
        "Top LIME Features:\n"
    )

    f.write(
        "-" * 60
        + "\n"
    )

    for feature, weight in lime_features:

        f.write(
            f"{feature}\t"
            f"{weight:+.6f}\n"
        )


print(
    f"\nLIME text explanation saved to:"
)

print(
    text_path
)


# ============================================================
# COMPLETE
# ============================================================

print("\n")
print("=" * 60)
print("ML PIPELINE + LIME COMPLETE")
print("=" * 60)

print(
    "\nAlexNet was used only for feature extraction."
)

print(
    "The ML classifiers operate on page-level "
    "4096-dimensional AlexNet features."
)

print(
    f"\nBest classifier: "
    f"{best_classifier_name}"
)

print(
    f"LIME explanation generated for "
    f"test sample {LIME_SAMPLE_INDEX}."
)